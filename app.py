import streamlit as st

import db
import agents.recon_crawler as recon_crawler
import agents.api_hunter as api_hunter
import agents.api_mapper as api_mapper
import agents.nmap_cve as nmap_cve
import agents.reporter as reporter

st.set_page_config(page_title="SOAR Dashboard", layout="wide")
db.init_db()

# --- Session control (sidebar) -------------------------------------------
st.sidebar.title("Session")

known_sessions = db.get_sessions()
current = db.get_config("active_session", "default")
options = sorted(set(known_sessions + [current]))

choice = st.sidebar.selectbox("Active session", options=options, index=options.index(current))
new_session = st.sidebar.text_input("Or create new session")

if st.sidebar.button("Set active session"):
    target_session = new_session.strip() or choice
    db.set_config("active_session", target_session)
    st.rerun()

session_id = db.get_config("active_session", "default")
st.sidebar.markdown(f"**Current session:** `{session_id}`")

tab_recon, tab_hunter, tab_map, tab_nmap, tab_report, tab_all = st.tabs(
    ["Auto Recon", "API Hunter", "API Mapper", "Nmap + CVE Scan", "Reporter", "All Findings"]
)

# --- Auto Recon (replaces mitmdump) ----------------------------------------
with tab_recon:
    st.subheader("Automated Recon Crawler")
    st.caption("Headless browser visits the target and auto-follows same-origin links. No manual browsing needed.")
    url = st.text_input("Target URL (e.g. https://10.10.x.x or https://xyz.web-security-academy.net)")
    max_pages = st.slider("Max pages to crawl", 1, 50, 10)

    if st.button("Run recon", disabled=not url):
        with st.spinner(f"Crawling up to {max_pages} pages and capturing traffic..."):
            result = recon_crawler.run(session_id, url, max_pages=max_pages)
        st.success(f"Visited {result['pages_visited']} pages, captured {result['requests_captured']} requests")

    targets = db.get_targets(session_id, finding_type="raw_traffic")
    target_filter = st.selectbox("View captured traffic for", options=["(all)"] + targets)
    raw = db.get_findings(
        session_id=session_id,
        finding_type="raw_traffic",
        target=None if target_filter == "(all)" else target_filter,
    )
    st.write(f"{len(raw)} captured requests stored")
    for f in raw[-50:]:
        label = f"[{f['agent']}] {f['data'].get('method')} {f['data'].get('url')} -> {f['data'].get('res_status')}"
        with st.expander(label):
            st.json(f["data"])

# --- API Hunter (active fuzzing) --------------------------------------------
with tab_hunter:
    st.subheader("API Hunter Agent")
    st.caption("LLM generates likely undocumented paths, then actually probes the target for them.")
    hunt_url = st.text_input("Base URL", key="hunt_url")
    app_context = st.text_input("App context (e.g. 'ecommerce site with a cart and user accounts')")

    if st.button("Run API hunt", disabled=not (hunt_url and app_context)):
        try:
            with st.spinner("Generating candidate paths and probing..."):
                result = api_hunter.run(session_id, hunt_url, app_context)

            paths_tried = result["paths_tried"]
            found = result["found"]
            status_counts = result["status_counts"]

            if not paths_tried:
                st.error("The LLM's response couldn't be parsed into any paths. Check the raw Ollama output in your terminal.")
            else:
                st.success(f"Tried {len(paths_tried)} paths, found {len(found)} responsive")
                for entry in found:
                    st.write(f"`{entry['status']}` {entry['url']}")

                error_count = status_counts.get("error", 0)
                if error_count == len(paths_tried):
                    st.error(
                        "Every single request failed (connection/DNS error) - "
                        "check the base URL includes http:// or https:// and is reachable from this machine."
                    )
                elif error_count:
                    st.warning(f"{error_count} requests failed outright (see details below).")

                with st.expander("Diagnostics: paths tried & status breakdown"):
                    st.write("**Status code breakdown:**", {k: v for k, v in status_counts.items() if k != "error_examples"})
                    if "error_examples" in status_counts:
                        st.write("**Sample errors:**")
                        for ex in status_counts["error_examples"][:5]:
                            st.code(ex)
                    st.write("**Paths generated by the LLM:**")
                    st.code("\n".join(paths_tried))
        except RuntimeError as e:
            st.error(str(e))

# --- API Mapper --------------------------------------------------------
with tab_map:
    st.subheader("API Mapper Agent")
    targets = db.get_targets(session_id, finding_type="raw_traffic")
    target = st.selectbox("Target to map", options=targets) if targets else None

    if st.button("Generate API map", disabled=not target):
        try:
            with st.spinner("Asking Qwen2.5-Coder..."):
                yaml_out = api_mapper.run(session_id, target)
            if yaml_out:
                st.success("Done")
                st.code(yaml_out, language="yaml")
            else:
                st.warning("No raw traffic found for this target yet - run Auto Recon first.")
        except RuntimeError as e:
            st.error(str(e))

    existing = db.get_findings(session_id=session_id, finding_type="api_endpoint", target=target)
    if existing:
        st.markdown("**Previous maps / discovered endpoints for this target:**")
        for f in reversed(existing[-10:]):
            with st.expander(f"{f['agent']} - {f['created_at']}"):
                st.json(f["data"])

# --- Nmap + CVE ----------------------------------------------------------
with tab_nmap:
    st.subheader("Nmap + CVE Matcher")
    st.caption("Needs the 'nmap' binary on this host, and network reach to the target (VPN if it's a THM box).")
    ip = st.text_input("Target IP (e.g. 10.10.x.x)")

    if st.button("Run scan", disabled=not ip):
        with st.spinner("Running nmap -sV (can take a minute or two)..."):
            services = nmap_cve.run(session_id, ip)
        st.success(f"Found {len(services)} services")

    results = db.get_findings(session_id=session_id, finding_type="cve_match", target=ip) if ip else []
    for f in results:
        d = f["data"]
        label = f"Port {d['port']}/{d['protocol']} - {d.get('product') or '?'} {d.get('version') or ''}"
        with st.expander(label):
            if d["cves"]:
                for c in d["cves"]:
                    st.markdown(f"**{c['id']}**: {c['description']}")
            else:
                st.write("No CVEs matched.")

# --- Reporter --------------------------------------------------------------
with tab_report:
    st.subheader("Reporter Agent")
    st.caption("Pulls EVERYTHING stored for this session, regardless of which agents produced it.")
    notes = st.text_area("Analyst notes (optional)")

    if st.button("Generate report"):
        try:
            with st.spinner("Asking Llama 3.2 to draft report..."):
                report = reporter.run(session_id, notes)
            st.markdown(report)
            st.download_button("Download as Markdown", report, file_name=f"report_{session_id}.md")
        except RuntimeError as e:
            st.error(str(e))

# --- Raw findings browser ---------------------------------------------------
with tab_all:
    st.subheader("All findings (raw)")
    all_findings = db.get_findings(session_id=session_id)
    st.write(f"{len(all_findings)} total findings in session `{session_id}`")
    for f in all_findings:
        label = f"[{f['finding_type']}] {f['agent']} - {f['target'] or ''} - {f['created_at']}"
        with st.expander(label):
            st.json(f["data"])